print("=== Частина 3: Використання операторів ===")

# Арифметичні оператори (виконують математичні обчислення)
a = 10
b = 3

print("--- Арифметичні оператори ---")
print(f"Початкові значення: a = {a}, b = {b}")
print(f"1. Додавання (a + b): {a + b}")
print(f"2. Віднімання (a - b): {a - b}")
print(f"3. Множення (a * b): {a * b}")
print(f"4. Звичайне ділення (a / b): {a / b}")
print(f"5. Цілочисельне ділення без остачі (a // b): {a // b}")
print(f"6. Остача від ділення (a % b): {a % b}")
print(f"7. Піднесення до степеня (a ** b): {a ** b}")

# Оператори порівняння (повертають True або False)
print("\n--- Оператори порівняння ---")
print(f"Рівність (a == b): {a == b}")
print(f"Нерівність (a != b): {a != b}")
print(f"Більше (a > b): {a > b}")
print(f"Менше (a < b): {a < b}")
print(f"Більше або дорівнює (a >= b): {a >= b}")
print(f"Менше або дорівнює (a <= b): {a <= b}")

# Логічні оператори (для комбінування умов)
print("\n--- Логічні оператори ---")
x = True
y = False
print(f"Логічне ТА (x and y): {x and y}")  # True, якщо обидва True
print(f"Логічне АБО (x or y): {x or y}")   # True, якщо хоча б одне True
print(f"Логічне НЕ (not x): {not x}")       # Змінює значення на протилежне

# Оператори комбінованого присвоєння
print("\n--- Оператори присвоєння ---")
c = 5
print(f"Початкове значення c = {c}")
c += 3  # Еквівалент: c = c + 3
print(f"Після c += 3 значення c = {c}")
c *= 2  # Еквівалент: c = c * 2
print(f"Після c *= 2 значення c = {c}")