# 2. Оголошення змінних різних типів даних
# ------------------------------------------
# У цьому блоці створюємо змінні для збереження різних типів інформації:
# - int (ціле число)
# - float (число з плаваючою крапкою)
# - str (текстовий рядок)
# - bool (логічний тип: True або False)
# - list (список - впорядкована колекція елементів)
# - tuple (кортеж - незмінна колекція)
# - dict (словник - колекція пар "ключ-значення")

age = 16                     # Ціле число (Integer)
height = 1.75                # Дійсне число (Float)
name = "Віктор"              # Текстовий рядок (String)
is_student = True            # Логічне значення (Boolean)
skills = ["C#", "Python"]    # Список (List)
coords = (10, 20)            # Кортеж (Tuple)
user_info = {"role": "User"} # Словник (Dictionary)

print("=== Частина 2: Змінні, їх значення та типи ===")
# Функція type() повертає тип даних змінної
print(f"Змінна 'age': значення = {age}, тип = {type(age)}")
print(f"Змінна 'height': значення = {height}, тип = {type(height)}")
print(f"Змінна 'name': значення = {name}, тип = {type(name)}")
print(f"Змінна 'is_student': значення = {is_student}, тип = {type(is_student)}")
print(f"Змінна 'skills': значення = {skills}, тип = {type(skills)}")
print(f"Змінна 'coords': значення = {coords}, тип = {type(coords)}")
print(f"Змінна 'user_info': значення = {user_info}, тип = {type(user_info)}")
print("-" * 40)

